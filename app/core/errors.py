from enum import StrEnum


class ErrorCode(StrEnum):
    # Fetch level: no usable page was obtained.
    MALFORMED_RESPONSE = "MALFORMED_RESPONSE"
    CONTRACT_OR_AUTH = "CONTRACT_OR_AUTH"
    UPSTREAM_UNAVAILABLE = "UPSTREAM_UNAVAILABLE"
    # Run level: a bug or infrastructure failure inside the gateway, not the vendor's fault.
    INTERNAL_ERROR = "INTERNAL_ERROR"
    # Page level.
    ENVELOPE_CHANGED = "ENVELOPE_CHANGED"
    PAGINATION_LOOP = "PAGINATION_LOOP"
    BATCH_THRESHOLD = "BATCH_THRESHOLD"
    # Record level.
    MALFORMED_RECORD = "MALFORMED_RECORD"
    MISSING_CRITICAL_FIELD = "MISSING_CRITICAL_FIELD"
    MISSING_IMPORTANT_FIELD = "MISSING_IMPORTANT_FIELD"
    MISSING_OPTIONAL_FIELD = "MISSING_OPTIONAL_FIELD"
    TYPE_CHANGED = "TYPE_CHANGED"
    BAD_FORMAT = "BAD_FORMAT"
    UNKNOWN_ENUM_VALUE = "UNKNOWN_ENUM_VALUE"
    ORPHAN_REFERENCE = "ORPHAN_REFERENCE"
